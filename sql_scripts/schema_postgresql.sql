-- ============================================================================
CREATE OR REPLACE VIEW vwstationlateststatus AS
SELECT
    t1.lngstationautoid,
    tblmatchstationstatus_1.intstatusid AS curstatus
FROM (
    SELECT
        lngstationautoid,
        MAX(lngstationstatusid) AS lateststatuschange
    FROM tblmatchstationstatus
    GROUP BY lngstationautoid
) AS t1
INNER JOIN tblmatchstationstatus AS tblmatchstationstatus_1
    ON t1.lateststatuschange = tblmatchstationstatus_1.lngstationstatusid;


-- ============================================================================
-- 12. vwguiresult4home
--     Source: [dbo].[vwGUIResult4Home]
--     Tables: sample, statuslookup, analysis, trims.lscresult,
--             trims.electrolysis, trims.deuteriumenrichment,
--             trims.lscloadlist  (all confirmed)
--     Fix:    ISNULL(sl1.Description, sl.Description) ->
--               COALESCE(sl1.description, sl.description)
--             TOP (100) PERCENT ... ORDER BY removed
--             SQL Server chained LEFT JOIN ... ON ... ON ... rewritten to
--               explicit standard LEFT JOINs
--             NULLIF(..., '') preserved (valid PostgreSQL)
--     Validated: EXPLAIN OK
-- ============================================================================
CREATE OR REPLACE VIEW vwguiresult4home AS
SELECT
    s.mediaid,
    a.analysisid,
    s.prefix,
    s.sampleid,
    s.sname,
    s.submissionid,
    s.status                                                         AS samplestatus,
    NULLIF(COALESCE(sl1.description, sl.description), '')            AS astatus,
    s.status,
    lr.finalactivity,
    lr.activityunit,
    lr.finalactivityunc,
    lr.rejectflag,
    lr.lldstatus,
    e.runid                                                          AS elysrunid,
    ll.runid                                                         AS lscrunid,
    lr.enrichmentfactor,
    lr.enrichmentfactorunc,
    de.predeuterium,
    de.postdeuterium,
    ll.countid
FROM sample AS s
INNER JOIN statuslookup AS sl
    ON sl.status = s.status
LEFT OUTER JOIN analysis AS a
    ON s.sampleid = a.sampleid
LEFT OUTER JOIN trims.lscresult AS lr
    ON a.analysisid = lr.analysisid
LEFT OUTER JOIN trims.electrolysis AS e
    ON a.analysisid = e.analysisid
LEFT OUTER JOIN trims.deuteriumenrichment AS de
    ON e.electrolysisid = de.electrolysisid
LEFT OUTER JOIN trims.lscloadlist AS ll
    ON lr.analysisid = ll.analysisid AND lr.runid = ll.runid
LEFT OUTER JOIN statuslookup AS sl1
    ON sl1.status = a.status
WHERE s.submissionid <> 1;


-- ============================================================================
-- 13. vwsampleanalysisstatus
--     Source: [dbo].[vwSampleAnalysisStatus]
--     Tables: sample, submission, analysis, statuslookup, workflow
--             CONCAT_WS supported in PostgreSQL 9.4+
--             COALESCE valid in PostgreSQL as-is
--     Validated: EXPLAIN OK
-- ============================================================================
CREATE OR REPLACE VIEW vwsampleanalysisstatus AS
SELECT
    s.prefix,
    s.sampleid,
    s.sname                                      AS samplename,
    s.mediaid,
    CONCAT_WS('-', s.prefix, s.sampleid::text)   AS ourlabid,
    a.analysisid,
    s.submissionid,
    COALESCE(a.status, s.status)                 AS status,
    stat.description,
    w.abbreviation::text AS abbreviation,
    a.repeats,
    a.precursoranalysisid
FROM sample AS s
INNER JOIN submission AS sub
    ON s.submissionid = sub.submissionid
LEFT OUTER JOIN analysis AS a
    ON s.sampleid = a.sampleid AND s.prefix = a.prefix
LEFT OUTER JOIN statuslookup AS stat
    ON stat.status = COALESCE(a.status, s.status)
LEFT JOIN workflow w
    ON a.workflowid = w.workflowid
WHERE sub.submissiontype <> 1;


